import { api } from '../client'
import type { ConfirmItem } from '@/features/syllabus/review'

/**
 * The syllabus import: the upload, the draft the review screen reads, and the
 * confirm.
 *
 * **Nothing is written until the student confirms.** The upload answers 202 with a
 * draft id, the extraction rides the existing `ingest_source` job (A250) and writes
 * a draft row, and `POST /syllabus/:id/confirm` is the only thing that produces
 * `events`, `tasks` and `goals` rows. So the draft read is a **poll**: `409
 * conflict` while the model is still reading, then `200` with the items.
 *
 * The draft body carries no score per item — the list arrives already ordered by
 * it, with a `needs_check` flag and the **evidence quote** (A261). This module
 * transcribes the route rather than re-deciding any of that, and it hands the raw
 * `items` array to `review.ts`, which is the one place a wire row becomes a row the
 * screen may render.
 */

/** The extraction's lifecycle, as `GET /syllabus/:id/draft` reports it. */
export type DraftStatus = 'pending' | 'extracting' | 'ready' | 'failed' | 'confirmed'

/** `POST /workspaces/:id/syllabus` — 202. */
export interface UploadResult {
  draft_id: string
  source_id: string
}

/** `GET /syllabus/:id/draft`, field for field. */
export interface DraftBody {
  draft_id: string
  source_id: string
  status: DraftStatus
  error: string | null
  course: { name?: string | null; code?: string | null; instructor?: string | null } | null
  /** The rows, pre-ordered, with the evidence quote and no score. */
  items: unknown[]
}

export const syllabusKeys = {
  draft: (draftId: string) => ['syllabus', draftId] as const,
}

/**
 * Uploads a syllabus.
 *
 * `FormData` is passed through the client untouched and gets no content-type: the
 * multipart boundary is generated by the browser, and a hand-written header would
 * omit it and break the parse.
 */
export async function uploadSyllabus(
  workspaceId: string,
  input: { file?: File; text?: string; title?: string },
): Promise<UploadResult> {
  const form = new FormData()
  if (input.file !== undefined) form.append('file', input.file)
  if (input.text !== undefined) form.append('text', input.text)
  if (input.title !== undefined) form.append('title', input.title)
  return api.post<UploadResult>(`/workspaces/${workspaceId}/syllabus`, form)
}

/**
 * The draft, as it stands.
 *
 * The caller polls this while the status is `extracting`: the route answers 409
 * for that state, because a 4xx for "still running" would force every client to
 * treat a normal outcome as an exception before it could show the message. So the
 * `ApiError` with code `conflict` is the *expected* answer here, and the screen
 * keeps polling.
 */
export async function fetchDraft(draftId: string, signal?: AbortSignal): Promise<DraftBody> {
  return api.get<DraftBody>(`/syllabus/${draftId}/draft`, { signal })
}

/**
 * `POST /syllabus/:id/confirm` — the only writer of the rows a syllabus produces.
 *
 * One transaction on the server: the draft must be `ready` and the caller's, and
 * every kept item's rows are written together. A second confirm is a 409 rather
 * than a second set of rows, which is what makes it safe to retry after a timeout.
 */
export async function confirmSyllabus(
  draftId: string,
  items: ConfirmItem[],
): Promise<{ events: number; tasks: number; goals: number }> {
  return api.post<{ events: number; tasks: number; goals: number }>(
    `/syllabus/${draftId}/confirm`,
    { items },
  )
}
