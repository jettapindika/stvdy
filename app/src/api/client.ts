import { apiErrorFromBody, ApiError } from './errors'
import {
  clearSession,
  getAccessToken,
  readDeviceId,
  readRefreshToken,
  saveSession,
  setAccessToken,
} from '../lib/tokens'

/**
 * The HTTP layer for the Phase 1 API.
 *
 * Three things live here and nothing else does:
 *
 * 1. **One place that attaches the bearer token.** The access token is read from
 *    memory at send time, so a refresh mid-flight is picked up by the next
 *    request without any caller knowing.
 * 2. **A single-flight refresh.** Every request that is refused with
 *    `unauthorized`/`token_expired` refreshes once and retries once. The refresh
 *    promise is shared, so ten concurrent 401s produce one `/auth/refresh` call
 *    and ten retries. Without the sharing, a screen that loads four queries at
 *    once would rotate the refresh token four times in parallel, and rotation is
 *    single-use: three of the four would present an already-rotated token and the
 *    server would revoke the whole session family. The bug would show up as
 *    "randomly signed out on load", which is exactly the kind of thing that
 *    survives review.
 * 3. **Typed errors.** Every non-2xx becomes an `ApiError` carrying the server's
 *    code, so callers branch on `code` and never on a message string.
 *
 * Requests to public routes pass `auth: false`. That is not just an optimisation:
 * a 401 from `/auth/login` means the password was wrong, and refreshing in
 * response to it would be nonsense (there is no session to refresh) and would
 * sign the user out of a session they still hold on another screen.
 */

/**
 * The API origin.
 *
 * `VITE_API_BASE_URL` is baked into the bundle at build time (Vite inlines
 * `import.meta.env.*`), so it must be set in the environment the build runs in,
 * not at runtime. It is not in any checked-in env file because it is a
 * deployment value, but it is documented in `.env.example`; its origin must also
 * be in the server's `WEB_ORIGIN` allowlist, or CORS blocks every request from
 * the built SPA.
 *
 * The fallback is deliberate and only correct for local development: with no
 * variable set, the build points at the dev server on `localhost:8080`. A
 * production build that forgets to set it therefore points at the developer's
 * own machine, which is a visible failure rather than a silent one.
 */
const RAW_BASE_URL = import.meta.env.VITE_API_BASE_URL ?? 'http://localhost:8080'

/** The API origin, without a trailing slash. Exported for Phase 2's stream reader. */
export const API_BASE_URL = RAW_BASE_URL.replace(/\/+$/, '')

export interface RequestOptions {
  method?: 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE'
  /**
   * A plain object is sent as JSON. `FormData` is passed through untouched and
   * gets no content-type, because the multipart boundary is generated by the
   * browser and a hand-written header would omit it and break the parse.
   */
  body?: unknown
  /** `false` for public routes: no bearer, and a 401 is a final answer. */
  auth?: boolean
  signal?: AbortSignal
}

/** The shape `/auth/refresh` returns. */
interface RefreshResponse {
  access_token: string
  refresh_token: string
  expires_at: string
}

let refreshInFlight: Promise<boolean> | null = null

function toApiError(error: unknown, fallback: string): ApiError {
  if (error instanceof ApiError) return error
  return new ApiError({
    status: 0,
    code: 'network',
    message: error instanceof Error && error.message ? error.message : fallback,
  })
}

async function readJson(response: Response): Promise<unknown> {
  const text = await response.text()
  // A 204 has no body, and neither does a 200 that answers with nothing. That is
  // not an error: several routes in this contract answer 204 by design.
  if (text.length === 0) return undefined
  try {
    return JSON.parse(text) as unknown
  } catch {
    return null
  }
}

function buildRequest(options: RequestOptions, token: string | null): RequestInit {
  const headers: Record<string, string> = { accept: 'application/json' }
  const init: RequestInit = {
    method: options.method ?? 'GET',
    headers,
  }
  if (options.signal) init.signal = options.signal

  if (token !== null) headers.authorization = `Bearer ${token}`

  if (options.body instanceof FormData) {
    init.body = options.body
  } else if (options.body !== undefined) {
    headers['content-type'] = 'application/json'
    init.body = JSON.stringify(options.body)
  }

  return init
}

/**
 * Ends the session and answers "was a usable session restored".
 *
 * Two different failures are deliberately not treated the same:
 *
 * - The server **rejected** the session (any 4xx, or a body without tokens):
 *   the refresh token is dead, so it is cleared. Keeping it would leave the app
 *   retrying a token that can never work and showing "signed in" around a
 *   session that cannot make a single request.
 * - The request **never arrived** (offline, a 5xx): nothing is known about the
 *   session, so it is kept. Signing a user out because their laptop dropped wifi
 *   is a worse failure than a request that has to be retried, and the retry is
 *   free once the network is back.
 */
async function performRefresh(): Promise<boolean> {
  const refreshToken = await readRefreshToken()
  const deviceId = await readDeviceId()
  if (refreshToken === null || deviceId === null) {
    await clearSession()
    return false
  }

  let response: Response
  try {
    response = await fetch(`${API_BASE_URL}/auth/refresh`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', accept: 'application/json' },
      body: JSON.stringify({ refresh_token: refreshToken, device_id: deviceId }),
    })
  } catch {
    return false
  }

  if (!response.ok) {
    if (response.status >= 400 && response.status < 500) await clearSession()
    return false
  }

  const body = (await readJson(response)) as Partial<RefreshResponse> | null
  if (typeof body?.access_token !== 'string' || typeof body.refresh_token !== 'string') {
    await clearSession()
    return false
  }

  setAccessToken(body.access_token)
  // The server rotates the refresh token on every use, so the stored one is
  // already stale and must be replaced before anything else runs.
  await saveSession({ refreshToken: body.refresh_token, deviceId })
  return true
}

/**
 * Refreshes the session, or joins the refresh that is already running.
 *
 * Exported because the app's bootstrap needs it on its own: on start there is no
 * access token and therefore nothing to get a 401 from.
 */
export function ensureFreshSession(): Promise<boolean> {
  if (refreshInFlight) return refreshInFlight
  const attempt = performRefresh().finally(() => {
    refreshInFlight = null
  })
  refreshInFlight = attempt
  return attempt
}

async function send<T>(path: string, options: RequestOptions, mayRefresh: boolean): Promise<T> {
  let response: Response
  try {
    response = await fetch(
      `${API_BASE_URL}${path}`,
      buildRequest(options, options.auth === false ? null : getAccessToken()),
    )
  } catch (error) {
    throw toApiError(error, `Could not reach the server at ${API_BASE_URL}.`)
  }

  if (!response.ok) {
    const error = apiErrorFromBody(response.status, await readJson(response))
    const isRefusedSession = error.isAuthFailure && options.auth !== false
    if (isRefusedSession && mayRefresh && (await ensureFreshSession())) {
      return send<T>(path, options, false)
    }
    throw error
  }

  return (await readJson(response)) as T
}

export function apiRequest<T>(path: string, options: RequestOptions = {}): Promise<T> {
  return send<T>(path, options, true)
}

/**
 * The five verbs, so a call site reads as the request it makes. `DELETE` and the
 * empty `POST`s return `void`: the contract answers 204 and there is nothing to
 * parse.
 */
export const api = {
  get: <T>(path: string, options: Omit<RequestOptions, 'method' | 'body'> = {}) =>
    apiRequest<T>(path, { ...options, method: 'GET' }),
  post: <T>(path: string, body?: unknown, options: Omit<RequestOptions, 'method' | 'body'> = {}) =>
    apiRequest<T>(path, { ...options, method: 'POST', body }),
  patch: <T>(path: string, body?: unknown, options: Omit<RequestOptions, 'method' | 'body'> = {}) =>
    apiRequest<T>(path, { ...options, method: 'PATCH', body }),
  put: <T>(path: string, body?: unknown, options: Omit<RequestOptions, 'method' | 'body'> = {}) =>
    apiRequest<T>(path, { ...options, method: 'PUT', body }),
  delete: <T = void>(path: string, options: Omit<RequestOptions, 'method' | 'body'> = {}) =>
    apiRequest<T>(path, { ...options, method: 'DELETE' }),
}
