import { useEffect } from 'react'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'

import { api } from '../client'

/**
 * Sources: the material a workspace reads across, and the ingestion status that
 * follows an upload.
 *
 * Ingestion is asynchronous on the server (upload returns 201 with a `pending`
 * source; a worker extracts, chunks, and embeds it), so the client cannot treat
 * a successful upload as a finished one. `useSourceStatus` is the other half of
 * that contract: it polls one source until the status is terminal, then stops.
 * Stopping is the important part. A poll that never stops is a request every few
 * seconds for the life of the tab, and it keeps a laptop's radio awake for no
 * information at all.
 */

export type SourceKind = 'pdf' | 'pptx' | 'docx' | 'url' | 'text' | 'web'
export type SourceStatusName = 'pending' | 'processing' | 'ready' | 'failed'

export interface Source {
  id: string
  workspace_id: string
  kind: SourceKind
  title: string
  url: string | null
  file_size: number | null
  mime: string | null
  status: SourceStatusName
  error: string | null
  created_at: string
}

export interface SourceStatus {
  id: string
  status: SourceStatusName
  chunk_count: number | null
  error: string | null
  /** When the row last changed, as the server reports it. */
  updated_at: string
}

export const sourceKeys = {
  list: (workspaceId: string) => ['workspaces', workspaceId, 'sources'] as const,
  status: (sourceId: string) => ['sources', sourceId, 'status'] as const,
}

/** Fast enough that a short PDF feels immediate, slow enough to be cheap. */
const STATUS_POLL_MS = 1500

export function isSettledStatus(status: SourceStatusName | undefined): boolean {
  return status === 'ready' || status === 'failed'
}

export function useSources(workspaceId: string) {
  return useQuery({
    queryKey: sourceKeys.list(workspaceId),
    queryFn: async ({ signal }) => {
      const body = await api.get<{ sources: Source[] }>(`/workspaces/${workspaceId}/sources`, {
        signal,
      })
      return body.sources
    },
    enabled: workspaceId.length > 0,
  })
}

export type UploadInput =
  | { kind: 'pdf' | 'docx' | 'pptx'; file: File; title?: string }
  | { kind: 'text'; text: string; title?: string }
  | { kind: 'url'; url: string; title?: string }

/** The kinds the add-source form offers. `web` is not one of them: it comes from a search hit. */
export const UPLOAD_KINDS = ['pdf', 'docx', 'pptx', 'url', 'text'] as const
export type UploadKind = (typeof UPLOAD_KINDS)[number]

/** The `accept` list for a file kind. The server enforces it; this is the file picker's filter. */
export function acceptFor(kind: UploadKind): string | undefined {
  switch (kind) {
    case 'pdf':
      return 'application/pdf,.pdf'
    case 'docx':
      return 'application/vnd.openxmlformats-officedocument.wordprocessingml.document,.docx'
    case 'pptx':
      return 'application/vnd.openxmlformats-officedocument.presentationml.presentation,.pptx'
    default:
      return undefined
  }
}

/**
 * Whether a typed URL is one this server will even try: `http(s)://` and a host.
 *
 * Client-side on purpose, and it is only an error message: the enforcement is the
 * server's `parse_target`, and a client check that disagreed with it would either
 * let a request through or block one the server would accept. This one catches the
 * common mistake — a bare `example.com` — before a round trip.
 */
export const HTTP_URL_PATTERN = /^https?:\/\/\S+$/i

export function useUploadSource(workspaceId: string) {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: (input: UploadInput) => {
      const form = new FormData()
      form.append('kind', input.kind)
      if (input.kind === 'text') form.append('text', input.text)
      else if (input.kind === 'url') form.append('url', input.url)
      else form.append('file', input.file, input.file.name)
      if (input.title !== undefined && input.title.length > 0) form.append('title', input.title)
      // FormData goes through untouched: the multipart boundary is generated by
      // the browser, and a content-type set by hand would omit it.
      return api.post<{ source: Source }>(`/workspaces/${workspaceId}/sources`, form)
    },
    onSuccess: () => queryClient.invalidateQueries({ queryKey: sourceKeys.list(workspaceId) }),
  })
}

export function useDeleteSource(workspaceId: string) {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: (sourceId: string) => api.delete(`/sources/${sourceId}`),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: sourceKeys.list(workspaceId) }),
  })
}

/**
 * The live status of one source.
 *
 * Every row asks for its own status once, because the list response carries the
 * status but not the chunk count, and a count that appears only for sources
 * ingested in this session would look like data going missing on the next load.
 * One request per source, cached by the query client, is the price of the row
 * telling the truth.
 *
 * A row that is still moving keeps asking; a row that has settled stops. Stopping
 * is the important part: a poll that never ends is a request every second and a
 * half for the life of the tab, keeping a phone's radio awake for information
 * that cannot change.
 */
export function useSourceStatus(workspaceId: string, sourceId: string, poll: boolean) {
  const queryClient = useQueryClient()

  const live = useQuery({
    queryKey: sourceKeys.status(sourceId),
    queryFn: async ({ signal }) => api.get<SourceStatus>(`/sources/${sourceId}/status`, { signal }),
    refetchInterval: (query) =>
      shouldKeepPolling(poll, query.state.data?.status) ? STATUS_POLL_MS : false,
  })

  const status = live.data?.status
  useEffect(() => {
    if (!isSettledStatus(status)) return
    // The list still shows the pre-ingestion status, so it is refetched once the
    // job settles: that is where the readable failure lands, and where the row
    // stops being a live query at all.
    void queryClient.invalidateQueries({ queryKey: sourceKeys.list(workspaceId) })
  }, [status, queryClient, workspaceId])

  return live
}

/**
 * Whether a row should keep asking.
 *
 * Once a live answer exists it decides on its own: the list's snapshot may be
 * older than the job. Before that, the list's status is the only information
 * there is.
 */
function shouldKeepPolling(poll: boolean, live: SourceStatusName | undefined): boolean {
  if (live === undefined) return poll
  return !isSettledStatus(live)
}
